const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'src/interception.js');

// These are classic-script source modules sharing the interceptor's existing
// scope. Concatenation preserves that scope without a bundler or runtime loader.
function buildInterceptor() {
    const sources = JSON.parse(fs.readFileSync(path.join(root, 'interceptor/sources.json'), 'utf8'));
    const output = '// Generated by scripts/build-interceptor.cjs. Edit interceptor/ instead.\n\n' +
        sources.map(file => `// Source: interceptor/${file}\n` +
            fs.readFileSync(path.join(root, 'interceptor', file), 'utf8').trimEnd() + '\n').join('\n');
    new vm.Script(output, { filename: outputPath });
    return output;
}

if (require.main === module) {
    const output = buildInterceptor();
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(outputPath, 'utf8') !== output) {
            console.error('src/interception.js is stale. Run npm run build.');
            process.exitCode = 1;
        }
    } else {
        fs.writeFileSync(outputPath, output);
        console.log('Built src/interception.js');
    }
}

module.exports = { buildInterceptor, outputPath };
